import {
  documentLanguage,
  type DocumentLanguage,
} from '@/modules/document-generation/document-language';

/**
 * The words in the Excel exports, in the reader's language. The web app
 * sends its own language as Accept-Language; without it (a direct API call)
 * the company's language is used, as for its documents. Payments,
 * receivables and the funnel used to come out with English headers and
 * English or raw status names ("NEW") in the Russian and Kyrgyz app.
 */
export function exportLanguage(
  acceptLanguage: string | undefined,
  companyLocale?: string | null,
): DocumentLanguage {
  const preferred = acceptLanguage?.split(',')[0]?.split(';')[0]?.trim();
  return documentLanguage(preferred || companyLocale);
}

